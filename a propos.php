<h2 class="text-success fw-bold mb-4">
Notre Histoire
</h2>

<p>
Depuis sa création, <strong>Doriane Agro Feed</strong> s'est donnée pour mission d'accompagner les éleveurs dans leur quête d'une alimentation animale de qualité. Installée au Marché B, Première Rue à Bafoussam, notre entreprise s'est progressivement imposée comme une référence grâce à la qualité de ses produits et à la confiance de sa clientèle.
</p>

<p>
Nous commercialisons des aliments pour volailles, porcs, bovins, lapins ainsi que des matières premières comme le maïs, le soja, le son, le palmiste, les vitamines et les compléments alimentaires. Notre objectif est d'améliorer les performances des élevages en proposant des produits fiables, accessibles et adaptés aux besoins des éleveurs.
</p>

</div>

